"""Noise injection on the surveys (two-country SI check 2b; task survey_noise_2c).

ROBUSTNESS ONLY. Can measurement error of the size present in platform
stance scores turn the survey contrast (U.S./China mean-|r| ratio 4.7) into
the platform contrast (1.3)? Independent Gaussian error is added to every
respondent's topic score in ANES and WVS so that each topic's reliability
(true-score variance / observed variance) equals ``rho``:

    x* = x + e,  e ~ N(0, var(x) (1 - rho) / rho)

and the 36 survey correlations, each country's mean |r|, the U.S.-Chinese
gap and the ratio are recomputed (pairwise complete, as the main analysis),
over ``n_draws`` noise draws (seed 0). Classical error multiplies each r by
sqrt(rho_i rho_j), so with equal reliability in both countries the gap
shrinks and the ratio stays; a different reliability per country (``rho_us``
vs ``rho_cn``) shows how unequal noise would have to be to reach 1.3.

The platform reliabilities come from the split-half check on the clusters
(SPEC check 2a); until they exist, ``rhos`` is a grid of assumed values.

    python -m robustness.survey_noise
    python -m robustness.survey_noise --rhos 0.62,0.48   # measured platform values
"""

from __future__ import annotations

import itertools
from pathlib import Path
from typing import Dict, List, Sequence

import numpy as np
import pandas as pd

from common.paths import SURVEY_DIR
from common.topics import CN_SURVEY_TOPICS, US_SURVEY_TOPICS

SOURCES = {"US": ("anes", [str(t) for t in US_SURVEY_TOPICS]), "CN": ("wvs", [str(t) for t in CN_SURVEY_TOPICS])}
PLATFORM = {"US": 0.146, "CN": 0.112}    # main-analysis platform mean |r| (stats Part 2)


def load() -> Dict[str, np.ndarray]:
    return {c: pd.read_stata(SURVEY_DIR / f"{src}.dta", convert_categoricals=False)[topics].to_numpy(float)
            for c, (src, topics) in SOURCES.items()}


def mean_abs_r(X: np.ndarray) -> float:
    """Mean |Pearson r| over all topic pairs, pairwise complete."""
    rs = []
    for i, j in itertools.combinations(range(X.shape[1]), 2):
        ok = ~np.isnan(X[:, i]) & ~np.isnan(X[:, j])
        rs.append(abs(np.corrcoef(X[ok, i], X[ok, j])[0, 1]))
    return float(np.mean(rs))


def add_noise(X: np.ndarray, rho: float, rng) -> np.ndarray:
    sd = np.sqrt(np.nanvar(X, axis=0) * (1 - rho) / rho)
    return X + rng.standard_normal(X.shape) * sd


def simulate(data: Dict[str, np.ndarray], rho_us: float, rho_cn: float, n_draws: int, seed: int = 0) -> Dict[str, np.ndarray]:
    rng = np.random.default_rng(seed)
    out = {"US": [], "CN": []}
    for _ in range(n_draws):
        out["US"].append(mean_abs_r(add_noise(data["US"], rho_us, rng)))
        out["CN"].append(mean_abs_r(add_noise(data["CN"], rho_cn, rng)))
    us, cn = np.array(out["US"]), np.array(out["CN"])
    return {"US": us, "CN": cn, "gap": us - cn, "ratio": us / cn}


def run(rhos: Sequence[float] = (0.9, 0.7, 0.5, 0.3), n_draws: int = 500) -> List[Path]:
    from common.paths import FIGURE_DIR, STATS_DIR, date_prefix

    if isinstance(rhos, str):
        rhos = [float(x) for x in rhos.split(",")]
    rhos = [float(r) for r in (rhos if isinstance(rhos, (list, tuple)) else [rhos])]
    data = load()
    base = {c: mean_abs_r(X) for c, X in data.items()}
    rows, equal = [], {}
    for rho in rhos:
        res = simulate(data, rho, rho, n_draws)
        equal[rho] = res
        rows.append(("equal", rho, rho, res))
    # Unequal noise: how unreliable would U.S. scores need to be (China at
    # each rho) for the survey ratio to fall to the platform ratio?
    target = PLATFORM["US"] / PLATFORM["CN"]
    unequal = []
    for rho_cn in rhos:
        for rho_us in np.round(np.arange(0.05, 1.0001, 0.05), 2):
            if rho_us > rho_cn:
                break
            res = simulate(data, float(rho_us), rho_cn, max(50, n_draws // 10))
            unequal.append((rho_cn, float(rho_us), float(res["ratio"].mean())))
    L = ["Paper statistics report  (task: survey_noise_2c)", "Generated by robustness/survey_noise.py.", "",
         "SOURCE: data/survey/anes.dta, data/survey/wvs.dta (main survey sources, nine topics each).",
         "CALCULATION: module docstring. Gaussian error with variance var(x)(1 - rho)/rho per topic; mean |r| over",
         f"  36 pairs (pairwise complete); {n_draws} draws per reliability (numpy seed 0); mean and 2.5-97.5% range.",
         "  Reliabilities are ASSUMED values until the platform split-half reliabilities (SPEC check 2a) exist.", "",
         f"No added noise: US {base['US']:.3f}, CN {base['CN']:.3f}, gap {base['US'] - base['CN']:.3f}, "
         f"ratio {base['US'] / base['CN']:.3f}",
         f"Platform (main analysis): US {PLATFORM['US']:.3f}, CN {PLATFORM['CN']:.3f}, gap {PLATFORM['US'] - PLATFORM['CN']:.3f}, "
         f"ratio {target:.3f}", "",
         "Equal reliability in both countries:",
         f"  {'rho':>5s}  {'US mean |r|':>12s}  {'CN mean |r|':>12s}  {'gap':>6s} {'range':16s}  {'ratio':>6s} {'range':16s}"]
    for _, rho, _, r in rows:
        q = lambda a: f"[{np.percentile(a, 2.5):.3f}, {np.percentile(a, 97.5):.3f}]"
        L.append(f"  {rho:5.2f}  {r['US'].mean():12.3f}  {r['CN'].mean():12.3f}  {r['gap'].mean():6.3f} {q(r['gap']):16s}  "
                 f"{r['ratio'].mean():6.3f} {q(r['ratio']):16s}")
    L += ["", f"Unequal reliability: survey ratio US/CN by (rho_CN, rho_US); target = platform ratio {target:.3f}",
          f"  ({max(50, n_draws // 10)} draws per cell)"]
    for rho_cn in rhos:
        cells = [(u, v) for c, u, v in unequal if c == rho_cn]
        # largest U.S. reliability that still brings the ratio down to the platform ratio
        hit = max((u for u, v in cells if v <= target), default=None)
        L.append(f"  rho_CN {rho_cn:.2f}: " + ", ".join(f"rho_US {u:.2f} -> {v:.2f}" for u, v in cells[::2])
                 + f"  | ratio <= {target:.2f} needs rho_US <= {hit if hit is not None else 'none'}"
                 + (f" (rho_US / rho_CN = {hit / rho_cn:.2f})" if hit is not None else ""))
    name = f"{date_prefix()}_survey_noise_2c_results"
    STATS_DIR.mkdir(parents=True, exist_ok=True)
    stats = STATS_DIR / f"{name}_stats.txt"
    stats.write_text("\n".join(L) + "\n")
    fig = figure(base, equal, FIGURE_DIR / f"{name}_fig.pdf")
    print(stats, fig, sep="\n")
    return [stats, fig]


def figure(base, equal, path: Path) -> Path:
    import matplotlib.pyplot as plt
    from plotting import figures as v4

    plt.rcParams["font.family"] = "Times New Roman"
    rhos = sorted(equal, reverse=True)
    x = [1.0] + rhos
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8))
    color = {"US": v4._TWITTER_COLOR, "CN": v4._WEIBO_COLOR}
    for c in ("US", "CN"):
        y = [base[c]] + [equal[r][c].mean() for r in rhos]
        axes[0].plot(x, y, marker="o", color=color[c], label=f"{c} survey + noise")
        axes[0].axhline(PLATFORM[c], color=color[c], ls=(0, (4, 2)), lw=1.2, label=f"{c} platform")
    axes[0].set_ylabel("Mean |r|")
    y = [base["US"] / base["CN"]] + [equal[r]["ratio"].mean() for r in rhos]
    lo = [np.nan] + [np.percentile(equal[r]["ratio"], 2.5) for r in rhos]
    hi = [np.nan] + [np.percentile(equal[r]["ratio"], 97.5) for r in rhos]
    axes[1].plot(x, y, marker="o", color="0.25", label="survey + equal noise")
    axes[1].fill_between(x, lo, hi, color="0.8")
    axes[1].axhline(PLATFORM["US"] / PLATFORM["CN"], color="0.25", ls=(0, (4, 2)), label="platform")
    axes[1].set_ylabel("Mean-|r| ratio, US / CN")
    axes[1].set_ylim(0, None)
    for ax, letter, title in zip(axes, "AB", ("Noise lowers both countries' |r|", "but leaves the ratio")):
        ax.set_xlabel("Reliability of each topic score (1 = no added noise)")
        ax.invert_xaxis()
        ax.set_title(title, fontsize=11, fontweight="bold")
        ax.legend(frameon=False, fontsize=8)
        ax.spines[["top", "right"]].set_visible(False)
        ax.text(-0.12, 1.05, letter, transform=ax.transAxes, fontsize=14, fontweight="bold", fontstyle="italic")
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, format="pdf", bbox_inches="tight")
    plt.close(fig)
    return path


if __name__ == "__main__":
    import fire

    fire.Fire(run)
